import assert from 'node:assert/strict';
import {readFileSync,existsSync,writeFileSync} from 'node:fs';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const base=fileURLToPath(new URL('../',import.meta.url)).replaceAll('\\','/');
const {default:catalog}=await import(pathToFileURL(base+'docs/editor/catalog.mjs'));
const {references,dictionarySheet}=await import(pathToFileURL(base+'docs/editor/references.mjs'));
const {excelSheets,workbookFiles}=await import(pathToFileURL(base+'docs/editor/core.mjs'));
const {default:fflate}=await import(pathToFileURL(base+'docs/editor/vendor/fflate.js'));
assert.equal(Object.keys(references).length,49);
assert.deepEqual(catalog.map(c=>c.id),Object.keys(references));
assert.equal(references.R15.sourceNumber,13);
assert.equal(references.R19.sourceNumber,14);
assert.equal(references.R33.sourceNumber,28);
assert.equal(references.R48.sourceNumber,42);
for(const id of ['R16','R17','R18','R47','R49','R50','R51'])assert.equal(references[id].kind,'adaptation');
for(const id of ['R27','R28'])assert.equal(references[id].panel,null);
for(const r of Object.values(references))for(const lang of ['es','en'])for(const field of ['definition','start','end','method','view','caveat'])assert.ok(r[lang][field]?.length>5);
const {panelImage}=await import(pathToFileURL(base+'docs/editor/reference-ui.mjs'));
for(const panel of ['1A','1B','2A','2B','2C'])assert.ok(existsSync(base+'docs/editor/'+panelImage(panel)));
for(const r of Object.values(references))if(r.panel)assert.ok(existsSync(base+'docs/editor/'+panelImage(r.panel)));
assert.equal(references.R03.panel,'1A');assert.equal(references.R15.panel,'1B');assert.equal(references.R23.panel,'2B');
const view=()=>({width:100,height:100,rois:[],knownCm:10,calibration:{points:[[0,0],[50,0]]},scaleNote:''});
const project={specimen:'Reference check',sex:'female',tlView:'Ventral',preferences:{},views:{Dorsal:view(),Ventral:view()}};
const sheets=excelSheets(project,catalog);
assert.deepEqual(sheets.map(s=>s.name),['Medidas','Copiar_dataset','Calibracion','Diccionario_medidas']);
assert.equal(sheets[1].rows.length,51);
assert.equal(sheets[3].rows.length,51);
assert.equal(sheets[3].rows[2][0],'R03');assert.equal(sheets[3].rows.at(-1)[0],'R51');
const files=workbookFiles(sheets);
const xml=new TextDecoder().decode(files['xl/worksheets/sheet4.xml']);
assert.ok(xml.includes('primera espina hemal'));assert.ok(xml.includes('first hemal spine'));
writeFileSync(join(mkdtempSync(join(tmpdir(),'radula-references-')),'reference-check.xlsx'),fflate.zipSync(files));
console.log('49 bilingual definitions, source mappings, assets, unchanged dataset ranges and exported dictionary verified.');
